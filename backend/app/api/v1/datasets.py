"""Dataset management routes for DataMind-King."""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException
from http import HTTPStatus
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.db import get_db
from app.models.dataset import Dataset
from app.models.user import User
from .schemas import DatasetCreate

router = APIRouter(prefix="", tags=["datasets"])


async def require_user(db: AsyncSession = Depends(get_db), user=None) -> User:
    """Placeholder dep — real auth injected via get_current_user in actual code."""
    return user  # type: ignore[return-value]


@router.get("", tags=["datasets-list"])
async def list_datasets(
    db: AsyncSession = Depends(get_db),
    user: User | None = Depends(require_user),
    limit: int = 50,
    offset: int = 0,
) -> dict:
    """List datasets for the current organization."""
    stmt = select(Dataset).where(Dataset.org_id == user.org_id).order_by(Dataset.created_at.desc()).offset(offset).limit(limit)
    result = await db.execute(stmt)
    datasets = result.scalars().all()
    return {"items": [d.__dict__ for d in datasets], "total": len(datasets)}


@router.post("", status_code=HTTPStatus.CREATED, tags=["datasets-create"])
async def create_dataset(
    body: DatasetCreate,
    db: AsyncSession = Depends(get_db),
    user: User | None = Depends(require_user),
) -> dict:
    """Register a new dataset."""
    ds = Dataset(
        id="",  # generated by caller
        org_id=user.org_id,
        name=body.name,
        description=body.description,
        storage_key=body.storage_key,
        file_size_bytes=body.file_size_bytes,
        checksum=body.checksum,
        status="pending",
    )
    db.add(ds)
    await db.commit()
    await db.refresh(ds)
    return ds.__dict__


@router.get("/{dataset_id}", tags=["datasets-get"])
async def get_dataset(
    dataset_id: str,
    db: AsyncSession = Depends(get_db),
    user: User | None = Depends(require_user),
) -> dict:
    """Get a single dataset, enforcing tenant isolation."""
    ds = (await db.execute(
        select(Dataset).where(
            (Dataset.id == dataset_id) & (Dataset.org_id == user.org_id)
        )
    )).scalar_one_or_none()
    if ds is None:
        raise HTTPException(status_code=HTTPStatus.NOT_FOUND, detail="Dataset not found")
    return ds.__dict__


@router.delete("/{dataset_id}", status_code=HTTPStatus.NO_CONTENT, tags=["datasets-delete"])
async def delete_dataset(
    dataset_id: str,
    db: AsyncSession = Depends(get_db),
    user: User | None = Depends(require_user),
) -> None:
    """Delete a dataset, enforcing tenant isolation."""
    ds = (await db.execute(
        select(Dataset).where(
            (Dataset.id == dataset_id) & (Dataset.org_id == user.org_id)
        )
    )).scalar_one_or_none()
    if ds is None:
        raise HTTPException(status_code=HTTPStatus.NOT_FOUND, detail="Dataset not found")
    await db.delete(ds)
    await db.commit()
